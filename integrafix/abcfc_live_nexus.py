class ActionStatus(Enum):
    PROPOSED = "proposed"       # Generated by nexus
    APPROVED = "approved"       # Passed risk checks
    EXECUTED = "executed"       # Trade placed
    FILLED = "filled"           # Order filled
    REJECTED = "rejected"       # Failed risk check
    CANCELLED = "cancelled"     # User or system cancelled


@dataclass
class LiveAction:
    """
    An executable action with real market data.

    Unlike theoretical Action, this has:
    - Real market/token IDs
    - Actual prices from order book
    - Calculated probabilities
    - Execution status
    """
    # Identity
    action_id: str
    created_at: str

    # Market info (real)
    market_id: str              # Polymarket condition ID
    market_slug: str            # Human readable
    token_id: str               # YES or NO token

    # Trade params (from order book)
    side: str                   # "YES" or "NO"
    size: float                 # Number of shares
    price: float                # Entry price
    limit_price: float          # Max price willing to pay

    # Probability estimate (real, not 50%)
    prob_estimate: float        # Our probability estimate
    market_prob: float          # Market implied probability
    edge: float                 # Our edge (prob_estimate - price)

    # ABCFC bounds (calculated from real data)
    worst_pnl: float            # If wrong
    best_pnl: float             # If right
    expected_pnl: float         # Edge * stake

    # Scoring
    nexus_score: float = 0.0
    risk_adjusted_score: float = 0.0

    # Execution
    status: ActionStatus = ActionStatus.PROPOSED
    order_id: Optional[str] = None
    fill_price: Optional[float] = None
    filled_size: Optional[float] = None

    # Outcome (after resolution)
    outcome: Optional[str] = None  # "won", "lost", "pending"
    realized_pnl: Optional[float] = None

    def to_dict(self) -> Dict:
        return {
            "action_id": self.action_id,
            "created_at": self.created_at,
            "market_slug": self.market_slug,
            "side": self.side,
            "size": self.size,
            "price": self.price,
            "prob_estimate": self.prob_estimate,
            "edge": self.edge,
            "worst_pnl": self.worst_pnl,
            "best_pnl": self.best_pnl,
            "expected_pnl": self.expected_pnl,
            "nexus_score": self.nexus_score,
            "status": self.status.value,
            "outcome": self.outcome,
            "realized_pnl": self.realized_pnl,
        }


