def main():
    import argparse

    parser = argparse.ArgumentParser(description="ABCFC Live Nexus")
    parser.add_argument("command", choices=[
        "status", "observe", "generate", "decide", "execute", "cycle"
    ], default="status", nargs="?")
    parser.add_argument("--risk", type=float, default=0.6, help="Risk aversion (0-1)")
    parser.add_argument("--live", action="store_true", help="Execute real trades")
    parser.add_argument("--min-edge", type=float, default=0.05, help="Minimum edge")
    args = parser.parse_args()

    nexus = ABCFCLiveNexus(
        risk_aversion=args.risk,
        dry_run=not args.live,
    )
    nexus.min_edge = args.min_edge

    if args.command == "status":
        nexus.observe()
        nexus.generate_actions()
        nexus.decide()
        nexus.print_status()

    elif args.command == "observe":
        result = nexus.observe()
        print(json.dumps(result, indent=2))

    elif args.command == "generate":
        nexus.observe()
        actions = nexus.generate_actions()
        print(f"Generated {len(actions)} actions:")
        for a in actions[:5]:
            print(f"  {a.market_slug[:30]} {a.side} @ {a.price:.2f} E={a.expected_pnl:.2f}")

    elif args.command == "decide":
        nexus.observe()
        nexus.generate_actions()
        approved = nexus.decide()
        print(f"Approved {len(approved)} actions:")
        for a in approved:
            print(f"  {a.market_slug[:30]} {a.side} @ {a.price:.2f} E={a.expected_pnl:.2f}")

    elif args.command == "execute":
        nexus.observe()
        nexus.generate_actions()
        approved = nexus.decide()
        results = nexus.execute(approved)
        print(json.dumps(results, indent=2))

    elif args.command == "cycle":
        result = nexus.run_cycle()
        print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
