@dataclass
class LiveMarketData:
    """Real market data for nexus evaluation."""
    market_id: str
    market_slug: str
    question: str

    # Current prices
    yes_price: float
    no_price: float
    mid_price: float
    spread: float

    # Order book depth
    yes_bid_depth: float        # Liquidity at bid
    yes_ask_depth: float        # Liquidity at ask
    no_bid_depth: float
    no_ask_depth: float

    # Volume
    volume_24h: float
    total_volume: float

    # Time
    end_date: Optional[str] = None
    days_to_resolution: float = 30.0

    # Our estimate (from wisdom engine or model)
    prob_estimate: Optional[float] = None

    @property
    def yes_edge(self) -> float:
        """Edge for YES position."""
        if self.prob_estimate is None:
            return 0.0
        return self.prob_estimate - self.yes_price

    @property
    def no_edge(self) -> float:
        """Edge for NO position."""
        if self.prob_estimate is None:
            return 0.0
        return (1 - self.prob_estimate) - self.no_price


