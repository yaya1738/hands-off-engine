    # =========================================================================
    # GENERATE - Create executable actions from opportunities
    # =========================================================================

    def generate_actions(self) -> List[LiveAction]:
        """
        Generate executable actions from real market opportunities.

        Only generates actions where:
        1. Edge > min_edge (profitable)
        2. Liquidity sufficient (can execute)
        3. Risk limits allow (position sizing)
        """
        self.proposed_actions = []

        # Calculate current exposure
        current_exposure = sum(
            p.get("size", 0) * p.get("entry_price", 0)
            for p in self.current_positions
        )
        available_capital = self.max_total_exposure - current_exposure

        if available_capital <= 0:
            return []

        for market_id, market in self.market_data.items():
            # Check if we have a probability estimate
            if market.prob_estimate is None:
                # Use market price as probability (no edge)
                continue

            # Check YES edge
            if market.yes_edge >= self.min_edge:
                # Calculate position size (Kelly or fixed)
                size = self._calculate_position_size(
                    edge=market.yes_edge,
                    price=market.yes_price,
                    available=available_capital,
                )

                if size > 0:
                    action = self._create_action(
                        market=market,
                        side="YES",
                        size=size,
                        price=market.yes_price,
                    )
                    self.proposed_actions.append(action)

            # Check NO edge
            if market.no_edge >= self.min_edge:
                size = self._calculate_position_size(
                    edge=market.no_edge,
                    price=market.no_price,
                    available=available_capital,
                )

                if size > 0:
                    action = self._create_action(
                        market=market,
                        side="NO",
                        size=size,
                        price=market.no_price,
                    )
                    self.proposed_actions.append(action)

        # Sort by expected P&L
        self.proposed_actions.sort(key=lambda a: a.expected_pnl, reverse=True)

        return self.proposed_actions

    def _calculate_position_size(self, edge: float, price: float,
                                  available: float) -> float:
        """Calculate position size using fractional Kelly."""
        if edge <= 0 or price <= 0 or price >= 1:
            return 0

        # Kelly fraction: edge / odds
        # For binary: f = (p * b - q) / b where b = (1-price)/price
        prob = price + edge
        b = (1 - price) / price

        kelly = (prob * b - (1 - prob)) / b if b > 0 else 0
        kelly = max(0, min(kelly, 0.25))  # Cap at 25% Kelly

        # Half Kelly for safety
        kelly *= 0.5

        # Size in dollars
        size = available * kelly

        # Cap at max position
        size = min(size, self.max_position_size)

        return round(size, 2)

    def _create_action(self, market: LiveMarketData, side: str,
                       size: float, price: float) -> LiveAction:
        """Create a LiveAction from market data."""
        # Calculate P&L bounds
        if side == "YES":
            worst_pnl = -size * price           # Lose entire stake
            best_pnl = size * (1 - price)       # Win (1 - price) per share
            expected_pnl = size * market.yes_edge
            prob = market.prob_estimate
        else:
            worst_pnl = -size * price
            best_pnl = size * (1 - price)
            expected_pnl = size * market.no_edge
            prob = 1 - market.prob_estimate

        # Score using ABCFC scoring
        score = self._score_action(worst_pnl, best_pnl, expected_pnl)

        return LiveAction(
            action_id=f"{market.market_slug}_{side}_{datetime.now().timestamp():.0f}",
            created_at=datetime.now(timezone.utc).isoformat(),
            market_id=market.market_id,
            market_slug=market.market_slug,
            token_id="",  # Would need actual token ID
            side=side,
            size=size,
            price=price,
            limit_price=price * 1.02,  # 2% slippage tolerance
            prob_estimate=prob,
            market_prob=market.yes_price if side == "YES" else market.no_price,
            edge=market.yes_edge if side == "YES" else market.no_edge,
            worst_pnl=worst_pnl,
            best_pnl=best_pnl,
            expected_pnl=expected_pnl,
            nexus_score=score,
            risk_adjusted_score=score,
        )

    def _score_action(self, worst: float, best: float, expected: float) -> float:
        """Score action using ABCFC methodology."""
        range_val = max(abs(best), abs(worst), 1)

        expected_norm = expected / range_val
        downside_norm = worst / range_val

        # Risk-adjusted score
        score = expected_norm * (1 - self.risk_aversion)
        score += downside_norm * self.risk_aversion

        return score * 100  # Scale to reasonable range

    # =========================================================================
    # SIMULATE - Calculate impacts with real probabilities
    # =========================================================================

    def simulate_portfolio_impact(self, action: LiveAction) -> Dict:
        """
        Simulate how action affects total portfolio ABCFC.

        Uses real data, not theoretical 50% assumptions.
        """
        # Current portfolio bounds
        current_worst = sum(p.get("worst_pnl", 0) for p in self.current_positions)
        current_best = sum(p.get("best_pnl", 0) for p in self.current_positions)
        current_expected = sum(p.get("expected_pnl", 0) for p in self.current_positions)

        # New bounds after action
        new_worst = current_worst + action.worst_pnl
        new_best = current_best + action.best_pnl
        new_expected = current_expected + action.expected_pnl

        return {
            "current": {
                "worst": current_worst,
                "best": current_best,
                "expected": current_expected,
            },
            "after": {
                "worst": new_worst,
                "best": new_best,
                "expected": new_expected,
            },
            "delta": {
                "worst": action.worst_pnl,
                "best": action.best_pnl,
                "expected": action.expected_pnl,
            },
            "score": action.nexus_score,
        }

    # =========================================================================
    # DECIDE - Select best actions
    # =========================================================================

    def decide(self, max_actions: int = 3) -> List[LiveAction]:
        """
        Select best actions from proposed set.

        Considers:
        - Individual action scores
        - Portfolio diversification
        - Risk limits
        """
        if not self.proposed_actions:
            return []

        # Filter by risk checks
        approved = []
        remaining_capital = self.max_total_exposure

        for action in self.proposed_actions:
            # Check position limit
            if action.size * action.price > remaining_capital:
                action.status = ActionStatus.REJECTED
                continue

            # Check edge requirement
            if action.edge < self.min_edge:
                action.status = ActionStatus.REJECTED
                continue

            action.status = ActionStatus.APPROVED
            approved.append(action)
            remaining_capital -= action.size * action.price

            if len(approved) >= max_actions:
                break

        return approved

    # =========================================================================
    # EXECUTE - Place trades
    # =========================================================================

    def execute(self, actions: List[LiveAction] = None) -> List[Dict]:
        """
        Execute approved actions.

        In dry_run mode, logs but doesn't place orders.
        """
        if actions is None:
            actions = [a for a in self.proposed_actions if a.status == ActionStatus.APPROVED]

        results = []

        for action in actions:
            if self.dry_run:
                result = {
                    "action_id": action.action_id,
                    "status": "DRY_RUN",
                    "market": action.market_slug,
                    "side": action.side,
                    "size": action.size,
                    "price": action.price,
                    "expected_pnl": action.expected_pnl,
                    "executed": False,
                }
            else:
                # Real execution
                result = self._execute_trade(action)

            results.append(result)
            self._log_action(action, result)

        return results

    def _execute_trade(self, action: LiveAction) -> Dict:
        """
        Execute actual trade via Polymarket API.
        INTEGRAFIX: Wired to credential_loader and py_clob_client.
        """
        if not self.client:
            return {
                "action_id": action.action_id,
                "status": "ERROR",
                "error": "No Polymarket client",
                "executed": False,
            }

        try:
            # INTEGRAFIX: Execute actual order
            from py_clob_client.clob_types import OrderArgs
            from py_clob_client.order_builder.constants import BUY, SELL

            token_id = action.token_id or action.market_slug
            side_const = BUY if action.side == "YES" else SELL

            order_args = OrderArgs(
                token_id=token_id,
                price=action.price,
                size=action.size,
                side=side_const
            )

            signed_order = self.client.create_order(order_args)
            result = self.client.submit_legacy_order(signed_order)

            order_id = result.get("orderID") or result.get("id") if result else None

            if order_id or result:
                action.status = ActionStatus.EXECUTED
                return {
                    "action_id": action.action_id,
                    "status": "EXECUTED",
                    "market": action.market_slug,
                    "side": action.side,
                    "size": action.size,
                    "order_id": str(order_id or result)[:50],
                    "executed": True,
                }
            else:
                action.status = ActionStatus.REJECTED
                return {
                    "action_id": action.action_id,
                    "status": "ERROR",
                    "error": "No order_id returned",
                    "executed": False,
                }

        except Exception as e:
            action.status = ActionStatus.REJECTED

            return {
                "action_id": action.action_id,
                "status": "ERROR",
                "error": str(e),
                "executed": False,
            }

    # =========================================================================
    # TRACK - Record outcomes and learn
    # =========================================================================

    def track_outcome(self, action_id: str, outcome: str, realized_pnl: float) -> Dict:
        """
        Record outcome of executed action.

        Feeds back to learning system for calibration.
        """
        # Find action
        action = None
        for a in self.executed_actions:
            if a.action_id == action_id:
                action = a
                break

        if not action:
            return {"error": f"Action {action_id} not found"}

        # Record outcome
        action.outcome = outcome
        action.realized_pnl = realized_pnl

        # Update state
        self._save_state()

        # Feed to learning
        self._feed_to_learning(action)

        return {
            "action_id": action_id,
            "outcome": outcome,
            "realized_pnl": realized_pnl,
            "expected_pnl": action.expected_pnl,
            "edge_realized": realized_pnl - action.expected_pnl,
        }

    def _feed_to_learning(self, action: LiveAction):
        """Feed outcome to learning system for calibration."""
        try:
            from integrafix.goals_effects_bridge import GoalsEffectsBridge, EffectType
            bridge = GoalsEffectsBridge()
            bridge.record_effect(
                name=f"Trade: {action.market_slug} {action.side}",
                description=f"Outcome: {action.outcome}, P&L: ${action.realized_pnl:.2f}",
                effect_type=EffectType.OUTCOME,
                value=action.realized_pnl,
                value_type="currency",
            )
        except:
            pass

        try:
            from autonomous.probability_calibrator import ProbabilityCalibrator
            calibrator = ProbabilityCalibrator()
            calibrator.record_prediction(
                prediction_id=action.action_id,
                predicted_prob=action.prob_estimate,
                actual_outcome=1 if action.outcome == "won" else 0,
            )
        except:
            pass

    # =========================================================================
    # FULL CYCLE
    # =========================================================================

    def run_cycle(self) -> Dict:
        """
        Run complete OBSERVE → GENERATE → DECIDE → EXECUTE cycle.
        """
        # 1. Observe
        obs = self.observe()

        # 2. Generate
        actions = self.generate_actions()

        # 3. Decide
        approved = self.decide()

        # 4. Execute
        results = self.execute(approved)

        # 5. Save state
        self._save_state()

        return {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "dry_run": self.dry_run,
            "observed": obs,
            "actions_generated": len(actions),
            "actions_approved": len(approved),
            "execution_results": results,
        }

    # =========================================================================
    # STATE MANAGEMENT
    # =========================================================================

    def _load_state(self):
        """Load state from disk."""
        if LIVE_NEXUS_STATE.exists():
            try:
                with open(LIVE_NEXUS_STATE) as f:
                    data = json.load(f)
                # Restore executed actions for tracking
            except:
                pass

    def _save_state(self):
        """Save state to disk."""
        state = {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "risk_aversion": self.risk_aversion,
            "dry_run": self.dry_run,
            "proposed_actions": len(self.proposed_actions),
            "executed_actions": len(self.executed_actions),
            "current_exposure": sum(p.get("size", 0) * p.get("entry_price", 0)
                                    for p in self.current_positions),
        }
        with open(LIVE_NEXUS_STATE, 'w') as f:
            json.dump(state, f, indent=2)

    def _log_action(self, action: LiveAction, result: Dict):
        """Log action to file."""
        entry = {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "action": action.to_dict(),
            "result": result,
        }
        with open(LIVE_NEXUS_LOG, 'a') as f:
            f.write(json.dumps(entry) + '\n')

    # =========================================================================
    # REPORTING
    # =========================================================================

    def print_status(self):
        """Print current nexus status."""
        print("=" * 70)
        print("ABCFC LIVE NEXUS STATUS")
        print(f"Generated: {datetime.now(timezone.utc).isoformat()}")
        print("=" * 70)

        print(f"\n>>> MODE: {'DRY RUN' if self.dry_run else 'LIVE'}")
        print(f"    Risk Aversion: {self.risk_aversion}")
        print(f"    Min Edge: {self.min_edge:.0%}")
        print(f"    Max Position: ${self.max_position_size}")

        print(f"\n>>> POSITIONS")
        print(f"    Current: {len(self.current_positions)}")
        exposure = sum(p.get("size", 0) * p.get("entry_price", 0)
                       for p in self.current_positions)
        print(f"    Exposure: ${exposure:.2f} / ${self.max_total_exposure}")

        print(f"\n>>> MARKETS SCANNED")
        print(f"    Markets: {len(self.market_data)}")
        with_edge = [m for m in self.market_data.values()
                     if m.prob_estimate and (abs(m.yes_edge) > self.min_edge or
                                              abs(m.no_edge) > self.min_edge)]
        print(f"    With Edge: {len(with_edge)}")

        print(f"\n>>> PROPOSED ACTIONS")
        print(f"    Total: {len(self.proposed_actions)}")
        approved = [a for a in self.proposed_actions if a.status == ActionStatus.APPROVED]
        print(f"    Approved: {len(approved)}")

        if approved:
            print(f"\n>>> TOP ACTIONS")
            for i, a in enumerate(approved[:3], 1):
                print(f"    {i}. {a.market_slug[:30]}")
                print(f"       {a.side} @ ${a.price:.2f} x {a.size:.0f}")
                print(f"       Edge: {a.edge:.1%} | E[P&L]: ${a.expected_pnl:.2f}")

        print("\n" + "=" * 70)

